// Ships the Shop's pictures with the game (owner, Oct 21: the catalog files say where every picture is). Each
// sourceImage in content/shop/*.json is downloaded once and processed the same way as the Studio does
// (lib/shopImages.ts: the cream background keyed out, 256 px and 768 px WebP), into public/shop-img/. The masters stay
// on Higgsfield and never reach players. lib/shopImagesStatic.ts (generated) maps each sku to its pictures, so items
// already on sale show them with no Studio step, and the Studio's import uses them instead of processing again.
//
// Usage: node --experimental-strip-types --no-warnings scripts/build-shop-images.ts   (npm run build:shop-images)
// Already-processed pictures are kept; delete public/shop-img/ to redo them all.
import { existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { SHOP_ITEMS } from "../lib/city.ts";
import { parseCatalogFile } from "../lib/shopCatalog.ts";
import { fetchSourceImage, imagePaths, processShopImage } from "../lib/shopImages.ts";

const DIR = "public/shop-img";
mkdirSync(DIR, { recursive: true });

// Every picture to make: the sku it's for, its source, whether it already has a transparent background.
const wanted: { sku: string; source: string; transparent: boolean }[] = [];
const missing: string[] = [];
for (const file of readdirSync("content/shop").filter((f) => f.endsWith(".json")).sort()) {
  const parsed = parseCatalogFile(JSON.parse(readFileSync(`content/shop/${file}`, "utf8")), file);
  for (const d of parsed.drafts) if (d.sourceImage) wanted.push({ sku: d.sku, source: d.sourceImage, transparent: d.transparent });
  for (const m of parsed.images) {
    const live = SHOP_ITEMS.filter((i) => i.name === m.liveName);
    if (!live.length) missing.push(`${file}: "${m.liveName}" isn't in the Shop`);
    for (const i of live) wanted.push({ sku: i.sku, source: m.sourceImage, transparent: m.transparent });
  }
}

const bySku: Record<string, { card: string; detail: string }> = {};
const done = new Map<string, { card: string; detail: string }>();
const failed: string[] = [];
let made = 0;
for (const w of wanted) {
  // One picture per source, whichever skus share it (a furniture line's colors, a reused sample).
  let pics = done.get(w.source);
  if (!pics) {
    const p = imagePaths(w.sku, w.source);
    pics = { card: `/shop-img/${p.card}`, detail: `/shop-img/${p.detail}` };
    if (!existsSync(`public${pics.card}`) || !existsSync(`public${pics.detail}`)) {
      try {
        const out = await processShopImage(await fetchSourceImage(w.source), w.transparent);
        writeFileSync(`public${pics.card}`, out.card);
        writeFileSync(`public${pics.detail}`, out.detail);
        made++;
      } catch (e) {
        failed.push(`${w.sku}: ${(e as Error).message}`);
        continue;
      }
    }
    done.set(w.source, pics);
  }
  bySku[w.sku] = pics;
}

const sorted = Object.fromEntries(Object.entries(bySku).sort(([a], [b]) => a.localeCompare(b)));
writeFileSync("lib/shopImagesStatic.ts", `// Generated by scripts/build-shop-images.ts: every Shop picture shipped with the game (public/shop-img/), by sku.
// Don't edit by hand; rerun the script after adding catalog files.

export const SHOP_STATIC_IMAGES: Record<string, { card: string; detail: string }> = ${JSON.stringify(sorted, null, 2)};
`);
console.log(`${Object.keys(sorted).length} items, ${done.size} pictures (${made} new)`);
for (const m of [...missing, ...failed]) console.log("  !", m);
if (failed.length) process.exitCode = 1;
